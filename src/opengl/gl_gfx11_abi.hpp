constexpr uint32_t spi_ps_input_front_face = 1u << 12;
constexpr uint32_t ps_vgpr_persp_i = 0;
constexpr uint32_t ps_vgpr_persp_j = 1;
constexpr uint32_t ps_vgpr_front_face = 2;       // nonzero = front facing
