constexpr uint32_t shader_entry_offset = 0;         // SPI_SHADER_PGM_LO_* = address >> 8
constexpr uint32_t shader_code_alignment = 256;     // code start and total size
constexpr uint32_t shader_tail_padding_min = 64;    // s_code_end bytes after the last instruction
constexpr uint32_t shader_max_bytes = 16384;        // generator output limit per program

// SPI_SHADER_PGM_RSRC4_*.INST_PREF_SIZE (128-byte units, at most 63 on GFX11).
constexpr uint32_t inst_pref_size(uint32_t code_bytes) noexcept {
    const uint32_t units = (code_bytes + 127u) / 128u;
    return units > 63u ? 63u : units;
}

// SPI_SHADER_PGM_RSRC1_*.VGPRS for wave32 (8-VGPR granules).
constexpr uint32_t rsrc1_vgpr_blocks(uint32_t vgpr_count) noexcept {
    return vgpr_count == 0 ? 0u : (vgpr_count + 7u) / 8u - 1u;
}

// FLOAT_MODE: round to nearest even, f32 and f16/f64 denormals preserved
// (FP_32_DENORMS 0x30 | FP_16_64_DENORMS 0xc0). DX10_CLAMP = 1, IEEE_MODE = 0.
constexpr uint32_t float_mode = 0xf0;

// Result of generating one program. All counts are for wave32.
struct ProgramInfo final {
    uint32_t code_dwords = 0;        // including s_code_end padding, multiple of 64
    uint32_t vgpr_count = 0;
    uint32_t sgpr_count = 0;         // highest SGPR used + 1 (RSRC1.SGPRS is ignored on GFX11)
    uint32_t user_sgpr_count = 0;    // RSRC2.USER_SGPR (+ USER_SGPR_MSB)
    uint32_t float_mode = 0;
    uint32_t lds_bytes = 0;          // RSRC2_GS.LDS_SIZE source; 0 for both stages
    uint32_t scratch_bytes = 0;      // always 0: SCRATCH_EN = 0
    // NGG vertex program.
    uint32_t es_vgpr_comp_cnt = 0;   // RSRC2_GS.ES_VGPR_COMP_CNT
    uint32_t gs_vgpr_comp_cnt = 0;   // RSRC1_GS.GS_VGPR_COMP_CNT
    uint32_t pos_export_count = 0;   // SPI_SHADER_POS_FORMAT POS0..POSn-1 = 4COMP
    uint32_t param_count = 0;        // SPI_VS_OUT_CONFIG.VS_EXPORT_COUNT = param_count - 1
    uint32_t max_es_verts = 0;       // GE_CNTL.VERTS_PER_SUBGRP, GE_MAX_OUTPUT_PER_SUBGROUP
    uint32_t max_gs_prims = 0;       // GE_CNTL.PRIMS_PER_SUBGRP
    uint32_t writes_attribute_ring = 0;
    // Pixel program.
    uint32_t spi_ps_input_ena = 0;   // also SPI_PS_INPUT_ADDR
    uint32_t interpolant_count = 0;  // SPI_PS_IN_CONTROL.NUM_INTERP
    uint32_t flat_mask = 0;          // SPI_PS_INPUT_CNTL_n.FLAT_SHADE per slot
    uint32_t col_format = 0;         // SPI_SHADER_COL_FORMAT
    uint32_t z_format = 0;           // SPI_SHADER_Z_FORMAT
    uint32_t kills = 0;              // DB_SHADER_CONTROL.KILL_ENABLE, early Z off
    uint32_t reads_front_face = 0;
};

// ---------------------------------------------------------------------------
// NGG geometry stage (merged ES+GS, wave32, non-passthrough primitive generation).
// One subgroup is one wave: at most 32 vertices and 32 primitives, so wave 0 is
// the only wave and merged_wave_info holds the subgroup counts.
// ---------------------------------------------------------------------------
constexpr uint32_t ngg_max_verts_per_subgroup = 32;
constexpr uint32_t ngg_max_prims_per_subgroup = 32;

// Values the backend programs (field positions from gfx11.json).
constexpr uint32_t ge_cntl = ngg_max_prims_per_subgroup |          // PRIMS_PER_SUBGRP [8:0]
                             (ngg_max_verts_per_subgroup << 9) |   // VERTS_PER_SUBGRP [17:9]
                             (252u << 21);                         // PRIM_GRP_SIZE [29:21]
constexpr uint32_t ge_max_output_per_subgroup = ngg_max_verts_per_subgroup;
constexpr uint32_t ge_ngg_subgrp_cntl = 1;                        // PRIM_AMP_FACTOR = 1
constexpr uint32_t vgt_gs_max_vert_out = 1;
// VGT_GS_OUT_PRIM_TYPE per primitive kind: POINTLIST 0, LINESTRIP 1, TRISTRIP 2.
constexpr uint32_t vgt_gs_out_prim_type(uint32_t vertices_per_primitive) noexcept {
    return vertices_per_primitive == 1 ? 0u : (vertices_per_primitive == 2 ? 1u : 2u);
}
constexpr uint32_t vgt_primitiveid_en = 0;
// ES_EN = ES_STAGE_REAL [4:3], PRIMGEN_EN [13], MAX_PRIMGRP_IN_WAVE = 2 [18:15],
// GS_W32_EN [22]; PRIMGEN_PASSTHRU_EN and PRIMGEN_PASSTHRU_NO_MSG stay 0 because the
// shader sends GS_ALLOC_REQ and builds its own primitive export.
constexpr uint32_t vgt_shader_stages_en = (2u << 3) | (1u << 13) | (2u << 15) | (1u << 22);
constexpr uint32_t spi_shader_idx_format = 1;                     // SPI_SHADER_1COMP
constexpr uint32_t spi_shader_pos_format = 4;                     // POS0 = SPI_SHADER_4COMP
// GL 1.1 exposes zero user clip planes and the frontend draws polygons filled, so
// no misc vector, clip distances or edge flags are exported. Points and lines take
// their size and width from PA_SU_POINT_SIZE / PA_SU_POINT_MINMAX / PA_SU_LINE_CNTL
// (USE_VTX_POINT_SIZE = 0): the VS never exports a point size.
constexpr uint32_t pa_cl_vs_out_cntl = 0;
// VPORT_{X,Y,Z}_{SCALE,OFFSET}_ENA and VTX_W0_FMT (the VS exports clip space).
constexpr uint32_t pa_cl_vte_cntl = 0x3fu | (1u << 10);
// PA_SU_SC_MODE_CNTL bits the shaders rely on: PROVOKING_VTX_LAST (GL), POLY_MODE 0.
constexpr uint32_t pa_su_sc_mode_cntl_required = 1u << 19;

constexpr uint32_t spi_vs_out_config(uint32_t param_count) noexcept {
    return ((param_count == 0 ? 0u : param_count - 1u) << 1) | (param_count == 0 ? 1u << 7 : 0u);
}

// System SGPRs written by the SPI for the merged stage.
constexpr uint32_t vs_sgpr_merged_wave_info = 3;  // [7:0] ES verts, [15:8] GS prims, [27:24] wave id
constexpr uint32_t vs_sgpr_attr_offset = 5;       // [14:0] ring offset in 512-byte units
constexpr uint32_t vs_system_sgprs = 8;

// User SGPRs: SPI_SHADER_USER_DATA_GS_i lands in s(8 + i).
constexpr uint32_t vs_user_data_first_sgpr = 8;
constexpr uint32_t vs_sgpr_vertex_buffer = 8;     // V#, 4 dwords (raw buffer)
constexpr uint32_t vs_sgpr_attribute_ring = 12;   // V#, 4 dwords (attribute ring)
constexpr uint32_t vs_sgpr_constants = 16;        // V#, 4 dwords (VertexConstants)
constexpr uint32_t vs_sgpr_base_vertex = 20;      // added to the vertex_id VGPR
constexpr uint32_t vs_user_sgpr_count = 13;       // RSRC2_GS.USER_SGPR (s8..s20)

// User-data dword index for each SGPR slot (SPI_SHADER_USER_DATA_GS_0 + 4 * index).
constexpr uint32_t vs_user_data_index(uint32_t sgpr) noexcept { return sgpr - vs_user_data_first_sgpr; }

// VGPRs written by the SPI (fixed positions for merged NGG shaders on GFX11).
constexpr uint32_t vs_vgpr_vertex_offsets01 = 0;  // [15:0] vertex 0, [31:16] vertex 1 (subgroup local)
constexpr uint32_t vs_vgpr_vertex_offsets23 = 1;  // [15:0] vertex 2
constexpr uint32_t vs_vgpr_prim_id = 2;
constexpr uint32_t vs_vgpr_invocation_id = 3;
constexpr uint32_t vs_vgpr_vertex_offsets45 = 4;
constexpr uint32_t vs_vgpr_vertex_id = 5;          // index buffer value (or auto index)
// GS_VGPR_COMP_CNT: points and lines need only VGPR0 (vertex offsets 0, 1);
// triangles also VGPR1 (vertex offset 2).
constexpr uint32_t vs_gs_vgpr_comp_cnt(uint32_t vertices_per_primitive) noexcept {
    return vertices_per_primitive == 3 ? 1u : 0u;
}
constexpr uint32_t vs_es_vgpr_comp_cnt = 0;        // vertex_id only

// GS_ALLOC_REQ payload in m0 and the GFX11 primitive export word.
constexpr uint32_t gs_alloc_req_payload(uint32_t vertices, uint32_t primitives) noexcept {
    return (vertices & 0x7ffu) | ((primitives & 0x7ffu) << 12);
}
constexpr uint32_t prim_export_index_bits = 10;    // vertex i at [10*i + 8 : 10*i]
constexpr uint32_t prim_export_null_bit = 1u << 31;
// Unused index fields (points: 1 and 2, lines: 2) are zero.
constexpr uint32_t prim_export_word(uint32_t v0, uint32_t v1, uint32_t v2) noexcept {
    return (v0 & 0x1ffu) | ((v1 & 0x1ffu) << 10) | ((v2 & 0x1ffu) << 20);
}

// ---------------------------------------------------------------------------
// Vertex records (little-endian float32), validated by the kernel as
// vertex_count * stride <= buffer bytes. Read with buffer_load_b128 through a raw V#.
// ---------------------------------------------------------------------------
constexpr uint32_t clip_record_stride = 80;
constexpr uint32_t clip_record_position = 0;      // clip x, y, z, w
constexpr uint32_t clip_record_front_color = 16;  // r, g, b, a
constexpr uint32_t clip_record_back_color = 32;   // r, g, b, a (two-sided only)
constexpr uint32_t clip_record_texcoord = 48;     // s, t, r, q (after the texture matrix)
constexpr uint32_t clip_record_fog = 64;          // fog factor, stipple position, line LOD, pad
constexpr uint32_t clip_record_stipple = 68;      // s at this vertex (lines with line_stipple)
constexpr uint32_t clip_record_line_lod = 72;     // gl_pipeline line_lod of the segment (lines)

