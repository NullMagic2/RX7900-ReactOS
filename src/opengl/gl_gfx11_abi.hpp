// Incremented on every change to anything in this header.
// v2: points and lines (vertices_per_primitive). v3: shader_max_bytes 16384
// (eight two-sided spot lights with fog and texturing need 10496 bytes).
// v4 (2026-10-24): 28-byte key with texture LOD filters, line and polygon
// stipple, GL_FRONT_AND_BACK (MRT0 + MRT1) and pixel-rectangle sources; the PS
// constant block and its V# in s20..s23; linear, position and depth/stencil
// export inputs. A key with every v4 field zero generates the v3 programs
// byte for byte.
constexpr uint32_t abi_version = 4;

// ---------------------------------------------------------------------------
// Shader key. A wire structure: the user-mode frontend derives it from GL state,
// the kernel validates it with key_valid and generates both programs from it.
// Equal keys produce byte-identical programs.
// ---------------------------------------------------------------------------

// vertex_input: what one vertex record holds (see the vertex record section).
constexpr uint8_t vertex_input_clip_space = 0;    // frontend-transformed, lit, fogged
constexpr uint8_t vertex_input_object_space = 1;  // shader transforms, lights, fogs

constexpr uint8_t fog_linear = 0;
constexpr uint8_t fog_exp = 1;
constexpr uint8_t fog_exp2 = 2;

constexpr uint8_t tex_env_modulate = 0;
constexpr uint8_t tex_env_decal = 1;
constexpr uint8_t tex_env_blend = 2;
constexpr uint8_t tex_env_replace = 3;

// GL base internal format of texture level 0 (selects the texture environment
// equations, as gl_raster shade_fragment does).
constexpr uint8_t texture_base_alpha = 0;
constexpr uint8_t texture_base_luminance = 1;
constexpr uint8_t texture_base_luminance_alpha = 2;
constexpr uint8_t texture_base_intensity = 3;
constexpr uint8_t texture_base_rgb = 4;
constexpr uint8_t texture_base_rgba = 5;

// Alpha function: fragment passes when (fragment alpha) FUNC (reference).
constexpr uint8_t compare_never = 0;
constexpr uint8_t compare_less = 1;
constexpr uint8_t compare_equal = 2;
constexpr uint8_t compare_lequal = 3;
constexpr uint8_t compare_greater = 4;
constexpr uint8_t compare_notequal = 5;
constexpr uint8_t compare_gequal = 6;
constexpr uint8_t compare_always = 7;

// min_filter (v4): texture_lod_none keeps the v3 single-filter sampling (the S#
// filter for minification and magnification alike); otherwise 1 + the GL
// minification filter and mag_filter the magnification filter, and the PS
// selects levels per fragment with the gl_pipeline texture_levels rules.
constexpr uint8_t texture_lod_none = 0;
constexpr uint8_t texture_min_nearest = 1;
constexpr uint8_t texture_min_linear = 2;
constexpr uint8_t texture_min_nearest_mipmap_nearest = 3;
constexpr uint8_t texture_min_linear_mipmap_nearest = 4;
constexpr uint8_t texture_min_nearest_mipmap_linear = 5;
constexpr uint8_t texture_min_linear_mipmap_linear = 6;
constexpr uint8_t texture_mag_nearest = 0;
constexpr uint8_t texture_mag_linear = 1;

// pixel_source (v4): a pixel rectangle (DrawPixels/Bitmap/CopyPixels) whose PS
// fetches its fragment data from the PS-constant image V# at the fragment's
// window position (gl_pipeline PixelFragments rule). Colour sources give the
// fragment colour, depth sources export Z, stencil sources export the stencil
// test value (the DB writes it with REPLACE under the write mask).
constexpr uint8_t pixel_source_none = 0;
constexpr uint8_t pixel_source_rgba8 = 1;          // R, G, B, A bytes (DrawPixels images)
constexpr uint8_t pixel_source_bgra8 = 2;          // B, G, R, A bytes (a colour buffer)
constexpr uint8_t pixel_source_coverage8 = 3;      // byte != 0 generates (Bitmap)
constexpr uint8_t pixel_source_depth32 = 4;        // float depth per pixel
constexpr uint8_t pixel_source_depth_copy = 5;     // X24_8_32 DB->CB copy: float depth at +0
constexpr uint8_t pixel_source_stencil8 = 6;       // stencil index byte per pixel
constexpr uint8_t pixel_source_stencil_copy = 7;   // X24_8_32 DB->CB copy: stencil byte at +4

constexpr bool pixel_source_depth(uint8_t source) noexcept {
    return source == pixel_source_depth32 || source == pixel_source_depth_copy;
}
constexpr bool pixel_source_stencil(uint8_t source) noexcept {
    return source == pixel_source_stencil8 || source == pixel_source_stencil_copy;
}
constexpr uint32_t pixel_source_bytes(uint8_t source) noexcept {
    return source == pixel_source_coverage8 || source == pixel_source_stencil8 ? 1u :
           source == pixel_source_depth_copy || source == pixel_source_stencil_copy ? 8u : 4u;
}

constexpr uint8_t color_material_none = 0;
constexpr uint8_t color_material_ambient = 1;
constexpr uint8_t color_material_diffuse = 2;
constexpr uint8_t color_material_ambient_and_diffuse = 3;

constexpr uint32_t max_lights = 8;

struct ShaderKey final {
    uint8_t vertex_input = vertex_input_clip_space;
    uint8_t smooth = 1;            // 0: flat shading, provoking vertex last
    uint8_t two_sided = 0;         // back colour param, PS selects by front_face
    uint8_t lighting = 0;          // object space only
    uint8_t light_mask = 0;        // bit i: light i enabled (object space + lighting)
    uint8_t positional_mask = 0;   // bit i: light i position.w != 0
    uint8_t spot_mask = 0;         // bit i: light i spot cutoff != 180
    uint8_t normalize = 0;         // GL_NORMALIZE (object space)
    uint8_t color_material = color_material_none;
    uint8_t fog = 0;
    uint8_t fog_mode = fog_exp;    // object space only; clip space carries the factor
    uint8_t textured = 0;
    uint8_t tex_env = tex_env_modulate;
    uint8_t texture_base = texture_base_rgba;
    uint8_t alpha_test = 0;
    uint8_t alpha_func = compare_always;
    uint8_t vertices_per_primitive = 3;  // 1 points, 2 lines, 3 triangles
    // v4 (zero: the v3 behaviour).
    uint8_t min_filter = texture_lod_none;
    uint8_t mag_filter = texture_mag_nearest;
    uint8_t line_stipple = 0;            // lines: PS discard from the misc slot's .y
    uint8_t polygon_stipple = 0;         // triangles: PS discard from the PS constants
    uint8_t front_and_back = 0;          // MRT0 (front) and MRT1 (back) get the colour
    uint8_t pixel_source = pixel_source_none;
    uint8_t pixel_transfer = 0;          // pixel source: PS-constant scale/bias or shift/offset
    uint8_t reserved[4] = {0, 0, 0, 0};  // must be zero
};
static_assert(sizeof(ShaderKey) == 28, "ShaderKey is a 28-byte wire structure");
// The v3 wire key: the first 17 bytes followed by three zero bytes.
constexpr uint32_t shader_key_v3_bytes = 20;

constexpr bool flag_ok(uint8_t value) noexcept { return value <= 1; }

// True when every field is in range and consistent. The kernel rejects any other key.
constexpr bool key_valid(const ShaderKey& key) noexcept {
    const bool object = key.vertex_input == vertex_input_object_space;
    return key.vertex_input <= vertex_input_object_space && flag_ok(key.smooth) &&
           flag_ok(key.two_sided) && flag_ok(key.lighting) && flag_ok(key.normalize) &&
           flag_ok(key.fog) && flag_ok(key.textured) && flag_ok(key.alpha_test) &&
           key.color_material <= color_material_ambient_and_diffuse &&
           key.fog_mode <= fog_exp2 && key.tex_env <= tex_env_replace &&
           key.texture_base <= texture_base_rgba && key.alpha_func <= compare_always &&
           key.vertices_per_primitive >= 1 && key.vertices_per_primitive <= 3 &&
           key.reserved[0] == 0 && key.reserved[1] == 0 && key.reserved[2] == 0 &&
           (key.positional_mask & static_cast<uint8_t>(~key.light_mask)) == 0 &&
           (key.spot_mask & static_cast<uint8_t>(~key.light_mask)) == 0 &&
           (object || (key.lighting == 0 && key.light_mask == 0 && key.normalize == 0 &&
                       key.color_material == color_material_none)) &&
           (key.lighting != 0 || key.light_mask == 0) &&
           // Object-space two-sided colour comes from two-sided lighting only.
           (!object || key.two_sided == 0 || key.lighting != 0) &&
           // v4 features are clip-space (backend) features.
           key.min_filter <= texture_min_linear_mipmap_linear && key.mag_filter <= texture_mag_linear &&
           (key.min_filter != texture_lod_none || key.mag_filter == texture_mag_nearest) &&
           (key.min_filter == texture_lod_none || key.textured != 0) &&
           flag_ok(key.line_stipple) && flag_ok(key.polygon_stipple) && flag_ok(key.front_and_back) &&
           flag_ok(key.pixel_transfer) && key.pixel_source <= pixel_source_stencil_copy &&
           (key.line_stipple == 0 || key.vertices_per_primitive == 2) &&
           (key.polygon_stipple == 0 || key.vertices_per_primitive == 3) &&
           (key.pixel_source == pixel_source_none || key.vertices_per_primitive == 3) &&
           (key.pixel_transfer == 0 || key.pixel_source != pixel_source_none) &&
           // GL 1.1 4.3.1: stencil indices bypass texturing, fog and alpha test.
           (!pixel_source_stencil(key.pixel_source) ||
            (key.textured == 0 && key.fog == 0 && key.alpha_test == 0 && key.front_and_back == 0)) &&
           (object ? key.min_filter == texture_lod_none && key.line_stipple == 0 && key.polygon_stipple == 0 &&
                         key.front_and_back == 0 && key.pixel_source == pixel_source_none
                   : true) &&
           key.reserved[3] == 0;
}

constexpr bool keys_equal(const ShaderKey& a, const ShaderKey& b) noexcept {
    return a.vertex_input == b.vertex_input && a.smooth == b.smooth &&
           a.two_sided == b.two_sided && a.lighting == b.lighting &&
           a.light_mask == b.light_mask && a.positional_mask == b.positional_mask &&
           a.spot_mask == b.spot_mask && a.normalize == b.normalize &&
           a.color_material == b.color_material && a.fog == b.fog &&
           a.fog_mode == b.fog_mode && a.textured == b.textured && a.tex_env == b.tex_env &&
           a.texture_base == b.texture_base && a.alpha_test == b.alpha_test &&
           a.alpha_func == b.alpha_func && a.vertices_per_primitive == b.vertices_per_primitive &&
           a.min_filter == b.min_filter && a.mag_filter == b.mag_filter &&
           a.line_stipple == b.line_stipple && a.polygon_stipple == b.polygon_stipple &&
           a.front_and_back == b.front_and_back && a.pixel_source == b.pixel_source &&
           a.pixel_transfer == b.pixel_transfer;
}

// The key's PS reads the PS constant block (v4 user SGPRs s20..s23).
constexpr bool uses_ps_constants(const ShaderKey& key) noexcept {
    return key.min_filter != texture_lod_none || key.line_stipple != 0 || key.polygon_stipple != 0 ||
           key.pixel_source != pixel_source_none;
}

// ---------------------------------------------------------------------------
// Attribute (parameter) slots. GFX11 has no parameter exports: the VS stores
// every slot to the attribute ring and the SPI loads them into PS LDS.
// Slots are compacted in this order: front colour, back colour, texcoord, fog.
// ---------------------------------------------------------------------------
constexpr uint32_t slot_none = 0xffu;

// The clip record's misc field (offset 64): .x fog factor, .y line stipple
// position, .z line texture LOD. One slot carries it when any part is used.
constexpr bool needs_misc_slot(const ShaderKey& key) noexcept {
    return key.fog != 0 || key.line_stipple != 0 ||
           (key.min_filter != texture_lod_none && key.vertices_per_primitive == 2);
}

struct AttributeLayout final {
    uint32_t front_color = 0;
    uint32_t back_color = slot_none;
    uint32_t texcoord = slot_none;
    uint32_t fog = slot_none;        // the misc slot: .x fog factor, .y stipple, .z line LOD
    uint32_t count = 1;
    uint32_t flat_mask = 0;          // bit n: SPI_PS_INPUT_CNTL_n.FLAT_SHADE
};

constexpr AttributeLayout attribute_layout(const ShaderKey& key) noexcept {
    AttributeLayout layout{};
    uint32_t next = 1;

    if (key.two_sided != 0) {
        layout.back_color = next++;
    }

    if (key.textured != 0) {
        layout.texcoord = next++;
    }

    if (needs_misc_slot(key)) {
        layout.fog = next++;
    }

    layout.count = next;

    if (key.smooth == 0) {
        layout.flat_mask = 1u | (layout.back_color != slot_none ? 1u << layout.back_color : 0u);
    }

    return layout;
}

