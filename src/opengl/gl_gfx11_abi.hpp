constexpr uint32_t vc_projection = 16;
constexpr uint32_t vc_normal_matrix = 32;
constexpr uint32_t vc_texture_matrix = 44;
constexpr uint32_t vc_light_model_ambient = 60;
constexpr uint32_t vc_front_material = 64;
constexpr uint32_t vc_back_material = 84;
constexpr uint32_t vc_material_dwords = 20;
constexpr uint32_t vc_fog = 104;
constexpr uint32_t vc_lights = 108;
constexpr uint32_t vc_light_dwords = 24;
constexpr uint32_t vertex_constants_bytes = (vc_lights + max_lights * vc_light_dwords) * 4u;
