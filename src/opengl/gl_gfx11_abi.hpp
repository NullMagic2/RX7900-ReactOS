constexpr uint32_t spi_baryc_cntl = 1u << 24;

constexpr uint32_t spi_shader_col_format = 9;    // COL0 = SPI_SHADER_32_ABGR (r, g, b, a)
constexpr uint32_t spi_shader_z_format = 0;      // SPI_SHADER_ZERO
constexpr uint32_t cb_shader_mask = 0xf;         // OUTPUT0_ENABLE
constexpr uint32_t db_shader_control_kill_enable = 1u << 6;
constexpr uint32_t spi_ps_in_control(uint32_t interpolants) noexcept {
    return (interpolants & 0x3fu) | (1u << 15);  // NUM_INTERP, PS_W32_EN
}
constexpr uint32_t spi_ps_input_cntl(uint32_t slot, bool flat) noexcept {
    return (slot & 0x3fu) | (flat ? 1u << 10 : 0u);  // OFFSET, FLAT_SHADE
}

// v4 pixel-stage inputs (SPI_PS_INPUT_ENA, gc_11_0_0_sh_mask.h). The SPI packs
// the enabled inputs into consecutive VGPRs in bit order: PERSP_CENTER (2),
// LINEAR_CENTER (2), POS_X_FLOAT, POS_Y_FLOAT (one each), FRONT_FACE.
constexpr uint32_t spi_ps_input_linear_center = 1u << 5;   // line stipple position
constexpr uint32_t spi_ps_input_pos_x = 1u << 8;           // pixel centre x (stipple, pixel rectangles)
constexpr uint32_t spi_ps_input_pos_y = 1u << 9;           // pixel centre y, hardware rows top-down

// First VGPR of an enabled input among the ones this ABI uses (0xff: disabled).
constexpr uint32_t ps_input_vgpr(uint32_t ena, uint32_t input) noexcept {
    const uint32_t order[5] = {spi_ps_input_persp_center, spi_ps_input_linear_center, spi_ps_input_pos_x,
                               spi_ps_input_pos_y, spi_ps_input_front_face};
    const uint32_t width[5] = {2, 2, 1, 1, 1};
    uint32_t next = 0;
    for (uint32_t i = 0; i < 5; ++i) {
        if (order[i] == input) {
            return (ena & input) != 0 ? next : 0xffu;
        }
        next += (ena & order[i]) != 0 ? width[i] : 0u;
    }
    return 0xffu;
}

// PS input enables of a key.
constexpr uint32_t ps_input_ena(const ShaderKey& key) noexcept {
    return spi_ps_input_persp_center | (key.line_stipple != 0 ? spi_ps_input_linear_center : 0u) |
           (key.polygon_stipple != 0 || key.pixel_source != pixel_source_none
                ? spi_ps_input_pos_x | spi_ps_input_pos_y : 0u) |
           (key.two_sided != 0 ? spi_ps_input_front_face : 0u);
}

// v4 user SGPRs: the PS constant block's raw V# after the v3 slots; keys using
// it have 24 user SGPRs and the primitive mask in s24 (v3 keys keep 20 / s20).
constexpr uint32_t ps_sgpr_constants = 20;
constexpr uint32_t ps_user_sgpr_count_v4 = 24;
constexpr uint32_t ps_user_sgprs(const ShaderKey& key) noexcept {
    return uses_ps_constants(key) ? ps_user_sgpr_count_v4 : ps_user_sgpr_count;
}

