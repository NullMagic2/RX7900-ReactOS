// Depth/stencil export (Mesa ac_get_spi_shader_z_format): Z alone is 32_R in
// MRTZ.x; the stencil test value alone is UINT16_ABGR with the index in
// MRTZ.x[23:16] (aco export_fs_mrtz, GFX11 single channel).
constexpr uint32_t spi_shader_z_32_r = 1;
constexpr uint32_t spi_shader_z_uint16_abgr = 7;
constexpr uint32_t spi_shader_z_format_of(const ShaderKey& key) noexcept {
    return pixel_source_depth(key.pixel_source) ? spi_shader_z_32_r :
           pixel_source_stencil(key.pixel_source) ? spi_shader_z_uint16_abgr : spi_shader_z_format;
}
// COL0 (and COL1 for GL_FRONT_AND_BACK) 32_ABGR; nothing for stencil sources.
constexpr uint32_t spi_shader_col_format_of(const ShaderKey& key) noexcept {
    return pixel_source_stencil(key.pixel_source) ? 0u :
           key.front_and_back != 0 ? spi_shader_col_format | (spi_shader_col_format << 4) : spi_shader_col_format;
}
constexpr uint32_t cb_shader_mask_of(const ShaderKey& key) noexcept {
    return pixel_source_stencil(key.pixel_source) ? 0u : key.front_and_back != 0 ? 0xffu : cb_shader_mask;
}

// ---------------------------------------------------------------------------
// Descriptors (GFX11 words, from ac_descriptors.c; field positions gfx11-rsrc.json).
// ---------------------------------------------------------------------------
struct BufferDescriptor final {
    uint32_t words[4] = {};
};

struct ImageDescriptor final {
    uint32_t words[8] = {};
};

struct SamplerDescriptor final {
    uint32_t words[4] = {};
};

constexpr uint32_t buf_dst_sel_xyzw = 4u | (5u << 3) | (6u << 6) | (7u << 9);
constexpr uint32_t format_32_float = 22;
constexpr uint32_t format_32_32_32_32_float = 63;
constexpr uint32_t format_8_8_8_8_unorm = 42;
constexpr uint32_t oob_select_structured_with_offset = 0;
constexpr uint32_t oob_select_raw = 3;

// Raw buffer (vertex records and VertexConstants): stride 0, NUM_RECORDS = bytes,
// OOB_SELECT_RAW so out-of-range loads return zero.
constexpr BufferDescriptor raw_buffer_descriptor(uint64_t address, uint32_t bytes) noexcept {
    BufferDescriptor d{};
    d.words[0] = static_cast<uint32_t>(address);
    d.words[1] = static_cast<uint32_t>(address >> 32) & 0xffffu;
    d.words[2] = bytes;
    d.words[3] = buf_dst_sel_xyzw | (format_32_float << 12) | (oob_select_raw << 28);
    return d;
}

// Attribute ring, as ac_build_attr_ring_descriptor: STRIDE = 16 * param_count,
// SWIZZLE_ENABLE = 3 (16-byte elements), INDEX_STRIDE = 2 (32 lanes),
// 32_32_32_32_FLOAT, OOB_SELECT_STRUCTURED_WITH_OFFSET, NUM_RECORDS = ring bytes.
// Per-wave layout the stores assume: wave base = ring base + gs_attr_offset[14:0] * 512;
// slot p of lane l (l < 32) is the 16 bytes at wave base + p * 512 + l * 16, i.e.
// each wave owns param_count * 512 contiguous bytes.
constexpr BufferDescriptor attribute_ring_descriptor(uint64_t address, uint32_t ring_bytes,
                                                     uint32_t param_count) noexcept {
    BufferDescriptor d{};
    d.words[0] = static_cast<uint32_t>(address);
    d.words[1] = (static_cast<uint32_t>(address >> 32) & 0xffffu) |
                 (((param_count * 16u) & 0x3fffu) << 16) | (3u << 30);
    d.words[2] = ring_bytes;
    d.words[3] = buf_dst_sel_xyzw | (format_32_32_32_32_float << 12) | (2u << 21) |
                 (oob_select_structured_with_offset << 28);
    return d;
}
constexpr uint32_t attribute_ring_wave_bytes(uint32_t param_count) noexcept {
    return param_count * 512u;
}

// 2D linear RGBA8 texture, one level. address is 256-byte aligned; pitch_texels is
// the row pitch in texels, a multiple of 64 (256 bytes) and >= width. Texel (x, y)
// is at address + (y * pitch_texels + x) * 4 bytes R, G, B, A; row 0 is GL t = 0.
constexpr ImageDescriptor texture_descriptor(uint64_t address, uint32_t width, uint32_t height,
                                             uint32_t pitch_texels) noexcept {
    ImageDescriptor d{};
    const uint32_t w = width - 1u;
    const uint32_t h = height - 1u;
    const uint32_t p = pitch_texels - 1u;
    d.words[0] = static_cast<uint32_t>(address >> 8);
    d.words[1] = (static_cast<uint32_t>(address >> 40) & 0xffu) | (format_8_8_8_8_unorm << 20) |
                 ((w & 3u) << 30);                                  // MAX_MIP = 0
    d.words[2] = ((w >> 2) & 0xfffu) | ((h & 0x3fffu) << 14);
    d.words[3] = 4u | (5u << 3) | (6u << 6) | (7u << 9) |            // DST_SEL XYZW
                 (9u << 28);                                         // TYPE 2D, SW_MODE linear
    d.words[4] = (p & 0x1fffu) | (((p >> 13) & 1u) << 13);           // DEPTH = pitch - 1, PITCH_MSB
    d.words[5] = 4u << 20;                                           // PERF_MOD = 4
    return d;
}

constexpr uint32_t tex_clamp_wrap = 0;             // GL_REPEAT
constexpr uint32_t tex_clamp_last_texel = 2;       // GL_CLAMP / GL_CLAMP_TO_EDGE (as gl_raster)
constexpr uint32_t tex_filter_point = 0;
constexpr uint32_t tex_filter_bilinear = 1;

// Level-0 sampler: the PS samples with image_sample_lz, so MIN and MAG use the same
// filter (gl_raster: nearest when either filter is GL_NEAREST, else bilinear);
// MIP_FILTER none, MIN/MAX_LOD 0, transparent black border.
constexpr SamplerDescriptor sampler_descriptor(uint32_t clamp_s, uint32_t clamp_t,
                                               uint32_t filter) noexcept {
    SamplerDescriptor d{};
    d.words[0] = (clamp_s & 7u) | ((clamp_t & 7u) << 3) | ((clamp_t & 7u) << 6);
    d.words[2] = ((filter & 3u) << 20) | ((filter & 3u) << 22);
    return d;
}

