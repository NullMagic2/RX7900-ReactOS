template <size_t N>
void exact_multi(const char* name, const char* args, const uint32_t (&expected)[N]) {
    MultiCase c;
    parse_multi(args, c);
    Model model;
    Dcn32BandwidthPlan plan{};
    const bool ready = model.bandwidth.configure(*model.workspace, c.inputs) == Dcn32BandwidthStatus::ready &&
                       model.bandwidth.validate(c.request, plan) == Dcn32BandwidthStatus::ready;
    expect(ready, name);
    std::vector<uint32_t> values;
    flatten_multi(plan, values);
    expect(values.size() == N, "multi-pipe field count matches the oracle key list");
    uint32_t mismatches = 0;
    for (size_t i = 0; i < N && i < values.size(); ++i) {
        if (values[i] != expected[i]) {
            if (mismatches++ < 4) {
                std::fprintf(stderr, "%s: field %zu = %u, oracle %u\n", name, i, values[i], expected[i]);
            }
        }
    }
    expect(ready && mismatches == 0, name);
}

void refusals() {
    Dcn32SocInputs none = table1();
    none.clocks.num_dcfclk_levels = 0;
    expect(configure(none) == Dcn32BandwidthStatus::clock_table_unavailable, "no DCFCLK DPM levels: no box");
    Dcn32SocInputs no_memclk = table1();
    no_memclk.clocks.levels[0].memclk_mhz = 0;
    expect(configure(no_memclk) == Dcn32BandwidthStatus::clock_table_unavailable,
           "no UCLK level 0: Linux keeps the one-state default box, which is refused");
    Dcn32SocInputs no_dtb = table1();
    no_dtb.clocks.levels[0].dtbclk_mhz = 0;
    no_dtb.clocks.dc_mode_limit.dtbclk_mhz = 0;
    expect(configure(no_dtb) == Dcn32BandwidthStatus::clock_table_unavailable,
           "build_synthetic_soc_states failure (no DTBCLK) is refused");
    Dcn32SocInputs no_ref = table1();
    no_ref.dchub_refclk_khz = 0;
    expect(configure(no_ref) == Dcn32BandwidthStatus::invalid_argument, "zero DCHUB reference clock");
    Dcn32SocInputs too_many = table1();
    too_many.clocks.num_dppclk_levels = dcn32_max_dpm_levels + 1;
    expect(configure(too_many) == Dcn32BandwidthStatus::invalid_argument, "more DPM levels than PMFW reports");

    // The largest table PMFW can report (8 distinct UCLK and FCLK levels) still fits:
    // the synthetic build inserts at most 23 states, so too_many_states is a guard only.
    Dcn32SocInputs widest = table1();
    for (uint32_t i = 0; i < dcn32_max_dpm_levels; ++i) {
        widest.clocks.levels[i].fclk_mhz = 400 + 250 * i;
        widest.clocks.levels[i].memclk_mhz = 96 + 150 * i;
        widest.clocks.levels[i].dcfclk_mhz = 506 + 130 * i;
    }
    widest.clocks.num_fclk_levels = dcn32_max_dpm_levels;
    widest.clocks.num_memclk_levels = dcn32_max_dpm_levels;
    widest.clocks.num_dcfclk_levels = dcn32_max_dpm_levels;
    widest.clocks.dc_mode_limit.fclk_mhz = 400 + 250 * 7;
    widest.clocks.dc_mode_limit.memclk_mhz = 96 + 150 * 7;
    widest.clocks.dc_mode_limit.dcfclk_mhz = 506 + 130 * 7;
    expect(configure(widest) == Dcn32BandwidthStatus::ready, "the widest PMFW table builds a bounded box");

    Model fresh;
    Dcn32BandwidthPlan plan{};
    plan.voltage_level = 77;
    expect(fresh.bandwidth.validate(request(Dcn32OutputSignal::display_port, mode_1080), plan) ==
               Dcn32BandwidthStatus::clock_table_unavailable, "validation before configuration");
    expect(plan.voltage_level == 77, "a refused validation leaves the output untouched");

    Dcn32PlaneRequest zero_pitch = request(Dcn32OutputSignal::display_port, mode_1080);
    zero_pitch.pitch_pixels = 0;
    expect(validate(table1(), zero_pitch, plan) == Dcn32BandwidthStatus::invalid_argument, "zero pitch");
    Dcn32PlaneRequest short_pitch = request(Dcn32OutputSignal::display_port, mode_1080);
    short_pitch.pitch_pixels = 1919;
    expect(validate(table1(), short_pitch, plan) == Dcn32BandwidthStatus::invalid_argument, "pitch below width");
    Dcn32PlaneRequest bad_otg = request(Dcn32OutputSignal::display_port, mode_1080);
    bad_otg.otg_instance = 4;
    expect(validate(table1(), bad_otg, plan) == Dcn32BandwidthStatus::invalid_argument, "OTG beyond OTG3");
    Timing interlaced_mode = mode_1080;
    interlaced_mode.flags |= interlaced;
    expect(validate(table1(), request(Dcn32OutputSignal::display_port, interlaced_mode), plan) ==
               Dcn32BandwidthStatus::invalid_argument, "interlaced timing");
    Timing no_blank = mode_1080;
    no_blank.h_total = 1930;
    expect(validate(table1(), request(Dcn32OutputSignal::display_port, no_blank), plan) ==
               Dcn32BandwidthStatus::invalid_argument, "horizontal blank below the DCN minimum");

    // 3840x2160@120 (1188 MHz): Linux applies ODM 2:1 to a single DP stream above
    // DCN3_2_VMIN_DISPCLK_HZ; this owner programs one pipe, so it is refused.
    Timing mode_2160_120 = mode_2160;
    mode_2160_120.pixel_clock_khz = 1188000;
    expect(validate(table1(), request(Dcn32OutputSignal::display_port, mode_2160_120), plan) ==
               Dcn32BandwidthStatus::needs_more_pipes, "pixel clock above 717 MHz needs ODM combine");

    // A 400 MHz DISPCLK cap makes DML32 choose ODM 2:1 for 2160p60 DP (oracle:
    // odm_combine=1, no_of_dpp=2); TMDS cannot use ODM and is unsupported (oracle:
    // dml_vlevel=num_states).
    Dcn32SocInputs slow = table1();
    slow.clocks.levels[0].dispclk_mhz = 400;
    slow.clocks.levels[0].dppclk_mhz = 400;
    slow.clocks.dc_mode_limit.dispclk_mhz = 400;
    slow.clocks.dc_mode_limit.dppclk_mhz = 400;
    expect(validate(slow, request(Dcn32OutputSignal::display_port, mode_2160), plan) ==
               Dcn32BandwidthStatus::needs_more_pipes, "DML32 ODM combine is refused");
    expect(validate(slow, request(Dcn32OutputSignal::tmds, mode_2160), plan) ==
               Dcn32BandwidthStatus::unsupported_mode, "DML32 unsupported mode is refused");

    // A 4-line vertical blank leaves no prefetch time at any level (oracle:
    // dml_vlevel=num_states); with DML32's MaxVRatioPre of 4 it is unsupported.
    expect(validate(table1(), request(Dcn32OutputSignal::display_port,
                                      {594000, 3840, 4400, 176, 88, 2160, 2164, 1, 1, sync}), plan) ==
               Dcn32BandwidthStatus::unsupported_mode, "a vertical blank too short for prefetch");
}

