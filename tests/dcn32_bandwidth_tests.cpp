// Parses an oracle_mp argument list into SoC inputs, a request and a current topology.
struct MultiCase final {
    Dcn32SocInputs inputs{};
    Dcn32PlaneRequest request{};
    Dcn32Topology current{};
};

void parse_multi(const char* text, MultiCase& c) {
    std::vector<long> v;
    for (const char* p = text; *p != 0;) {
        char* end = nullptr;
        v.push_back(std::strtol(p, &end, 10));
        p = end;
        while (*p == ' ') {
            ++p;
        }
    }
    size_t a = 0;
    auto next = [&]() { return static_cast<uint32_t>(v.at(a++)); };
    Dcn32PlaneRequest& r = c.request;
    r.signal = next() != 0 ? Dcn32OutputSignal::tmds : Dcn32OutputSignal::display_port;
    Timing& t = r.timing;
    t.pixel_clock_khz = next();
    t.width = next();
    t.h_total = next();
    t.h_front_porch = next();
    t.h_sync_width = next();
    t.height = next();
    t.v_total = next();
    t.v_front_porch = next();
    t.v_sync_width = next();
    t.flags = sync;
    Dcn32SocInputs& in = c.inputs;
    in.dchub_refclk_khz = next();
    in.dentist_vco_khz = next();
    in.num_chans = next();
    in.dram_channel_width_bytes = next();
    const uint32_t levels = next();
    for (uint32_t i = 0; i < levels; ++i) {
        Dcn32ClockLevel& l = in.clocks.levels[i];
        l = {next(), next(), next(), next(), next(), next(), next(), next()};
    }
    in.clocks.num_dcfclk_levels = next();
    in.clocks.num_fclk_levels = next();
    in.clocks.num_memclk_levels = next();
    in.clocks.num_socclk_levels = next();
    in.clocks.num_dtbclk_levels = next();
    in.clocks.num_dispclk_levels = next();
    in.clocks.num_dppclk_levels = next();
    Dcn32ClockLevel& d = in.clocks.dc_mode_limit;
    d.dcfclk_mhz = next();
    d.fclk_mhz = next();
    d.memclk_mhz = next();
    d.socclk_mhz = next();
    d.dtbclk_mhz = next();
    d.dispclk_mhz = next();
    d.dppclk_mhz = next();
    in.dram_clock_change_latency_100ns = next();
    in.sr_enter_exit_latency_100ns = next();
    in.sr_exit_latency_100ns = next();
    r.otg_instance = next();
    const bool dsc = next() != 0;
    r.dsc_slices_h = next();
    r.dsc_bits_per_pixel_x16 = next();
    if (!dsc) {
        r.dsc_slices_h = 0;
        r.dsc_bits_per_pixel_x16 = 0;
    }
    r.plane_count = next();
    for (uint32_t i = 0; i < r.plane_count; ++i) {
        Dcn32PlaneGeometry& g = r.planes[i];
        g.dst.x = static_cast<int32_t>(next());
        g.dst.y = static_cast<int32_t>(next());
        g.surface_width = next();
        g.surface_height = next();
        g.dst.width = static_cast<int32_t>(g.surface_width);
        g.dst.height = static_cast<int32_t>(g.surface_height);
        r.plane_pitch_pixels[i] = next();
    }
    r.pitch_pixels = r.plane_pitch_pixels[0];
    auto link = [](long value) { return value < 0 ? dcn32_no_pipe : static_cast<uint8_t>(value); };
    for (uint32_t i = 0; i < dcn32_topology_pipes; ++i) {
        Dcn32TopologyPipe& p = c.current.pipes[i];
        p.stream = v.at(a++) != 0;
        const long plane = v.at(a++);
        p.has_plane = plane >= 0;
        p.plane = static_cast<uint8_t>(plane >= 0 ? plane : 0);
        p.top = link(v.at(a++));
        p.bottom = link(v.at(a++));
        p.prev_odm = link(v.at(a++));
        p.next_odm = link(v.at(a++));
    }
    r.current = &c.current;
    r.allow_odm = true;
}

