// dcn-stream: SurfaceSizeInMALL[0] (Linux dcn32_calculate_mall_ways_from_bytes input
// for the stream owner's HUBP USE_MALL_SEL); oracle surface_size_in_mall values.
void mall_sizes() {
    struct Case {
        const char* name;
        Dcn32SocInputs (*table)();
        Dcn32OutputSignal signal;
        Timing timing;
        uint32_t bytes;
    };
    const Case cases[]{
        {"640x480 MALL bytes", table1, Dcn32OutputSignal::display_port, mode_480, 1228800},
        {"1080p60 MALL bytes", table1, Dcn32OutputSignal::tmds, mode_1080, 8294400},
        {"2160p60 MALL bytes", table1, Dcn32OutputSignal::display_port, mode_2160, 33177600},
        {"1600x900 two-state MALL bytes", table3, Dcn32OutputSignal::display_port,
         {106184, 1600, 1668, 24, 27, 900, 1061, 85, 51, sync}, 5760000},
    };
    for (const Case& c : cases) {
        Model model;
        Dcn32BandwidthPlan plan{};
        expect(model.bandwidth.configure(*model.workspace, c.table()) == Dcn32BandwidthStatus::ready &&
                   model.bandwidth.validate(request(c.signal, c.timing), plan) == Dcn32BandwidthStatus::ready &&
                   plan.mall_ss_size_bytes == c.bytes,
               c.name);
    }
}

Dcn32BandwidthStatus configure(const Dcn32SocInputs& inputs) {
    Model model;
    return model.bandwidth.configure(*model.workspace, inputs);
}

Dcn32BandwidthStatus validate(const Dcn32SocInputs& inputs, const Dcn32PlaneRequest& r, Dcn32BandwidthPlan& plan) {
    Model model;
    const Dcn32BandwidthStatus status = model.bandwidth.configure(*model.workspace, inputs);
    return status == Dcn32BandwidthStatus::ready ? model.bandwidth.validate(r, plan) : status;
}

