void multi_pipe() {
    // Golden plans: ODM 2:1 from the single-display power policy (3840x2160@120
    // DP), from DML need (DISPCLK capped at 400 MHz: 2160p60) and with DSC
    // (7680x4320@60 at 12 bpp, 8 slices; 3840x2160@144 at 16 bpp, 4 slices), and
    // two planes on a stream whose primary was on pipe 0 (1080p60 and 2160p60).
    exact_multi("ODM 2:1 power policy at 3840x2160@120 matches Linux", args_odm_4k120, expected_odm_4k120);
    exact_multi("ODM 2:1 with DSC at 7680x4320@60 matches Linux", args_odm_dsc_8k60, expected_odm_dsc_8k60);
    exact_multi("ODM 2:1 with DSC at 3840x2160@144 matches Linux", args_odm_dsc_4k144, expected_odm_dsc_4k144);
    exact_multi("two planes at 1080p60 match Linux", args_mpo_1080, expected_mpo_1080);
    exact_multi("two planes at 2160p60 match Linux", args_mpo_4k60, expected_mpo_4k60);
    exact_multi("DML-needed ODM 2:1 (400 MHz DISPCLK) matches Linux", args_odm_slow_2160p60,
                expected_odm_slow_2160p60);

    Dcn32BandwidthPlan plan{};
    {
        MultiCase c;
        parse_multi(args_odm_4k120, c);
        c.request.allow_odm = false;
        expect(validate(c.inputs, c.request, plan) == Dcn32BandwidthStatus::needs_more_pipes,
               "without the ODM opt-in the 717 MHz refusal stays");
    }
    {
        MultiCase c;
        parse_multi(args_odm_slow_2160p60, c);
        c.request.allow_odm = false;
        expect(validate(c.inputs, c.request, plan) == Dcn32BandwidthStatus::needs_more_pipes,
               "without the ODM opt-in a DML ODM decision is refused");
    }
    {
        // DEVIATION: with an overlay the ODM power policy is not applied (Linux
        // would split both planes over four pipes); one slice and two pipes.
        MultiCase c;
        parse_multi(args_odm_4k120, c);
        Dcn32PlaneRequest& r = c.request;
        r.plane_count = 2;
        r.planes[1] = r.planes[0];
        r.plane_pitch_pixels[1] = r.plane_pitch_pixels[0];
        r.planes[0] = Dcn32PlaneGeometry{640, 360, Dcn32Rect{64, 64, 640, 360}};
        r.plane_pitch_pixels[0] = 640;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::ready && plan.odm_slices == 1 &&
                   plan.pipe_count == 2 && plan.topology.pipes[0].plane == 0 && plan.topology.pipes[1].plane == 1 &&
                   plan.topology.pipes[1].top == 0 && plan.topology.pipes[0].bottom == 1,
               "an overlay at 3840x2160@120 keeps one ODM slice (the top plane on the OTG master)");
    }
    {
        // ODM needed by DML for two planes: refused (no windowed MPO + ODM).
        MultiCase c;
        parse_multi(args_odm_slow_2160p60, c);
        Dcn32PlaneRequest& r = c.request;
        r.plane_count = 2;
        r.planes[1] = r.planes[0];
        r.plane_pitch_pixels[1] = r.plane_pitch_pixels[0];
        r.planes[0] = Dcn32PlaneGeometry{640, 360, Dcn32Rect{64, 64, 640, 360}};
        r.plane_pitch_pixels[0] = 640;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::needs_more_pipes,
               "two planes that need ODM combine are refused");
    }
    {
        // resource_find_free_pipe_used_in_cur_mpc_blending_tree: the overlay pipe
        // stays the one the current blending tree used (pipe 2), not the lowest free.
        MultiCase c;
        parse_multi(args_mpo_1080, c);
        Dcn32Topology cur{};
        topology_start_stream(cur, 0, false);
        expect(topology_append_plane(cur, Dcn32Topology{}, 0), "current primary plane");
        cur.pipes[2].stream = true;
        cur.pipes[2].has_plane = true;
        cur.pipes[2].plane = 1;
        cur.pipes[2].top = 0;
        cur.pipes[0].bottom = 2;
        c.request.current = &cur;
        expect(validate(c.inputs, c.request, plan) == Dcn32BandwidthStatus::ready && plan.pipes[1].pipe == 2 &&
                   plan.topology.pipes[0].bottom == 2 && plan.topology.pipes[2].opp == 0,
               "the secondary DPP pipe is reused from the current MPC tree");
    }
    {
        MultiCase c;
        parse_multi(args_mpo_1080, c);
        Dcn32PlaneRequest r = c.request;
        r.planes[0].dst.width = 320;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::invalid_argument, "a scaled plane is refused");
        r = c.request;
        r.planes[0].dst.x = 1700;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::invalid_argument,
               "a plane beyond the active area is refused");
        r = c.request;
        r.plane_count = 3;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::invalid_argument, "three planes are refused");
        r = c.request;
        r.plane_pitch_pixels[0] = 600;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::invalid_argument,
               "an overlay pitch below its width is refused");
        r = c.request;
        r.signal = Dcn32OutputSignal::tmds;
        r.dsc_slices_h = 4;
        r.dsc_bits_per_pixel_x16 = 192;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::invalid_argument,
               "DSC on TMDS (HDMI FRL DSC) is refused");
        r = c.request;
        r.dsc_slices_h = 4;
        expect(validate(c.inputs, r, plan) == Dcn32BandwidthStatus::invalid_argument,
               "DSC slices without a bit rate are refused");
    }
    {
        // A one-plane plan describes its single pipe in the multi-pipe fields too.
        expect(validate(table1(), request(Dcn32OutputSignal::display_port, mode_1080), plan) ==
                   Dcn32BandwidthStatus::ready && plan.pipe_count == 1 && plan.odm_slices == 1 &&
                   plan.pipes[0].pipe == 0 && plan.pipes[0].vstartup_start == plan.vstartup_start &&
                   plan.pipes[0].det_buffer_size_kb == plan.det_buffer_size_kb &&
                   plan.pipes[0].dppclk_khz == plan.dpp_dppclk_khz &&
                   plan.pipes[0].dlg.refcyc_per_htotal == plan.dlg.refcyc_per_htotal &&
                   plan.topology.otg_master == 0 && topology_used_pipes(plan.topology) == 1,
               "a one-pipe plan mirrors its fields into pipes[0] and the topology");
    }
}

void workspace_storage() {
    std::vector<unsigned char> storage(dcn32_bandwidth_workspace_bytes() + 16);
    unsigned char* aligned = storage.data();
    while (reinterpret_cast<uintptr_t>(aligned) % 8 != 0) {
        ++aligned;
    }
    expect(construct_dcn32_bandwidth_workspace(nullptr, dcn32_bandwidth_workspace_bytes()) == nullptr,
           "null storage refused");
    expect(construct_dcn32_bandwidth_workspace(aligned, dcn32_bandwidth_workspace_bytes() - 1) == nullptr,
           "short storage refused");
    expect(construct_dcn32_bandwidth_workspace(aligned + 1, dcn32_bandwidth_workspace_bytes()) == nullptr,
           "misaligned storage refused");
    expect(construct_dcn32_bandwidth_workspace(aligned, dcn32_bandwidth_workspace_bytes()) != nullptr,
           "aligned storage accepted");
}

