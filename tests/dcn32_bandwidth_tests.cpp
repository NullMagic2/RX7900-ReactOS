// Model storage owned by the test (the native owner allocates it nonpaged).
struct Model final {
    std::vector<unsigned char> storage = std::vector<unsigned char>(dcn32_bandwidth_workspace_bytes() + 16);
    Dcn32BandwidthWorkspace* workspace = nullptr;
    Dcn32Bandwidth bandwidth;

    Model() {
        void* raw = storage.data();
        while (reinterpret_cast<uintptr_t>(raw) % 8 != 0) {
            raw = static_cast<unsigned char*>(raw) + 1;
        }
        workspace = construct_dcn32_bandwidth_workspace(raw, dcn32_bandwidth_workspace_bytes());
    }
};

void exact(const char* name, const Dcn32SocInputs& inputs, const Dcn32PlaneRequest& r, const uint32_t* expected) {
    Model model;
    expect(model.workspace != nullptr, "workspace constructs in aligned storage");
    expect(model.bandwidth.configure(*model.workspace, inputs) == Dcn32BandwidthStatus::ready, name);
    Dcn32BandwidthPlan plan{};
    expect(model.bandwidth.validate(r, plan) == Dcn32BandwidthStatus::ready, name);
    std::vector<uint32_t> values;
    flatten(plan, values);
    expect(values.size() == plan_fields, "plan field count matches the oracle key list");
    unsigned mismatches = 0;

    for (uint32_t i = 0; i < plan_fields && i < values.size(); ++i) {
        if (values[i] != expected[i]) {
            std::fprintf(stderr, "%s: field %u is %u, Linux %u\n", name, i, values[i], expected[i]);
            ++mismatches;
        }
    }

    expect(mismatches == 0, name);

    // A second validation of the same request in the same model is identical: each
    // validation starts from a fresh model (no state leaks between commits).
    Dcn32BandwidthPlan again{};
    Dcn32PlaneRequest other = request(Dcn32OutputSignal::display_port, mode_1080);
    expect(model.bandwidth.validate(other, again) == Dcn32BandwidthStatus::ready, "unrelated validation succeeds");
    expect(model.bandwidth.validate(r, again) == Dcn32BandwidthStatus::ready, "revalidation succeeds");
    std::vector<uint32_t> second;
    flatten(again, second);
    expect(second == values, "revalidation after another mode reproduces the plan");
}

